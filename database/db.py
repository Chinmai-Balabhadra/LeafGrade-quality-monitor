from datetime import datetime, timezone
import json
import logging
import os
from pathlib import Path
import sqlite3
from typing import Dict, List, Tuple, Optional, Any, Union

PROJECT_ROOT = Path(__file__).resolve().parent.parent

logger = logging.getLogger(__name__)

DEFAULT_DB_DIR = PROJECT_ROOT / "database"
DEFAULT_DB_PATH = DEFAULT_DB_DIR / "leaf_analysis.db"
DEFAULT_SCHEMA_PATH = DEFAULT_DB_DIR / "schema.sql"


def get_db_path(custom_path: Optional[Union[str, Path]] = None) -> Path:
    """Returns database path with environment override support."""
    if custom_path:
        return Path(custom_path)
    env_path = os.environ.get("DATABASE_PATH")
    if env_path:
        return Path(env_path)
    return DEFAULT_DB_PATH


def get_connection(db_path: Optional[Union[str, Path]] = None) -> sqlite3.Connection:
    """
    Creates and configures a SQLite connection with Row factory and WAL mode.

    Args:
        db_path: Optional path to the database file.

    Returns:
        sqlite3.Connection object.
    """
    target_path = get_db_path(db_path)
    target_path.parent.mkdir(parents=True, exist_ok=True)

    conn = sqlite3.connect(str(target_path), timeout=15.0)
    conn.row_factory = sqlite3.Row

    # Optimize concurrency and safety
    with conn:
        conn.execute("PRAGMA journal_mode=WAL;")
        conn.execute("PRAGMA foreign_keys=ON;")

    return conn


def init_db(
    db_path: Optional[Union[str, Path]] = None,
    schema_path: Optional[Union[str, Path]] = None
) -> None:
    """
    Initializes the database schema if tables do not already exist.

    Args:
        db_path: Target SQLite database file.
        schema_path: Path to schema.sql file.
    """
    target_schema = Path(schema_path) if schema_path else DEFAULT_SCHEMA_PATH
    if not target_schema.exists():
        raise FileNotFoundError(f"Schema file not found at: {target_schema}")

    schema_sql = target_schema.read_text(encoding="utf-8")
    conn = get_connection(db_path)
    try:
        with conn:
            conn.executescript(schema_sql)
        logger.info(f"Database initialized successfully at: {get_db_path(db_path)}")
    finally:
        conn.close()


def row_to_dict(row: sqlite3.Row) -> Dict[str, Any]:
    """Converts a SQLite row into a JSON-friendly dictionary."""
    d = dict(row)

    # Parse stored JSON strings
    if "top_three_json" in d and d["top_three_json"]:
        try:
            d["top_three"] = json.loads(d["top_three_json"])
        except (json.JSONDecodeError, TypeError):
            d["top_three"] = []
    else:
        d["top_three"] = []

    if "quality_assessment_json" in d and d["quality_assessment_json"]:
        try:
            d["quality_assessment"] = json.loads(d["quality_assessment_json"])
        except (json.JSONDecodeError, TypeError):
            d["quality_assessment"] = {}
    else:
        d["quality_assessment"] = {}

    # Format confidence percentage
    if "confidence" in d and d["confidence"] is not None:
        d["confidence_percent"] = round(float(d["confidence"]) * 100.0, 2)

    return d


def insert_analysis(record: Dict[str, Any], db_path: Optional[Union[str, Path]] = None) -> int:
    """
    Inserts a newly completed leaf analysis record.

    Args:
        record: Dictionary generated by LeafPredictor.predict() or route handler.
        db_path: Optional custom database file path.

    Returns:
        int: The auto-generated primary key ID of the inserted record.
    """
    init_db(db_path)  # Ensure table exists

    # Clean filename: basename only, never store absolute filesystem paths
    raw_source = record.get("source") or record.get("image_filename") or "uploaded_leaf.jpg"
    filename = Path(str(raw_source)).name

    # Normalize timestamp to UTC ISO 8601 string
    ts = record.get("timestamp") or datetime.now(timezone.utc).isoformat()

    # Extract fields with safe defaults
    species = record.get("species") or "Unknown"
    predicted_class = record.get("predicted_class") or "Unknown"
    confidence = float(record.get("confidence") or 0.0)

    # Determine visual health string ("Healthy" or "Diseased")
    if record.get("is_visually_healthy") is True or record.get("visual_health") == "Healthy":
        visual_health = "Healthy"
    else:
        visual_health = "Diseased"

    condition = record.get("condition") or "Unspecified condition"
    plucking_suitability = record.get("plucking_suitability") or "Conditional"
    
    # Status: "Certain" or "Uncertain"
    raw_status = record.get("status") or "SUCCESS"
    prediction_status = "Certain" if raw_status == "SUCCESS" else "Uncertain"

    top_three_json = json.dumps(record.get("top_three", []))
    quality_json = json.dumps(record.get("quality_assessment", {}))
    plucking_rec = record.get("plucking_recommendation", "")

    insert_sql = """
        INSERT INTO leaf_analysis (
            timestamp, image_filename, species, predicted_class,
            confidence, visual_health, condition, plucking_suitability,
            prediction_status, top_three_json, quality_assessment_json,
            plucking_recommendation
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?);
    """

    conn = get_connection(db_path)
    try:
        with conn:
            cursor = conn.cursor()
            cursor.execute(
                insert_sql,
                (
                    ts, filename, species, predicted_class,
                    confidence, visual_health, condition, plucking_suitability,
                    prediction_status, top_three_json, quality_json,
                    plucking_rec
                )
            )
            analysis_id = cursor.lastrowid
            logger.info(f"Saved analysis record #{analysis_id} for {predicted_class}")
            return analysis_id
    finally:
        conn.close()


def get_analysis_by_id(
    analysis_id: int,
    db_path: Optional[Union[str, Path]] = None
) -> Optional[Dict[str, Any]]:
    """Retrieves a single historical record by primary key."""
    init_db(db_path)
    conn = get_connection(db_path)
    try:
        cursor = conn.cursor()
        cursor.execute("SELECT * FROM leaf_analysis WHERE id = ?;", (analysis_id,))
        row = cursor.fetchone()
        if row is None:
            return None
        return row_to_dict(row)
    finally:
        conn.close()


def get_history(
    page: int = 1,
    limit: int = 10,
    species: Optional[str] = None,
    visual_health: Optional[str] = None,
    status: Optional[str] = None,
    search: Optional[str] = None,
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    db_path: Optional[Union[str, Path]] = None
) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    """
    Queries historical analysis records with pagination, filtering, and search.

    Returns:
        Tuple of (records_list, pagination_metadata_dict)
    """
    init_db(db_path)
    conn = get_connection(db_path)

    # Sanitize pagination parameters
    page = max(1, int(page))
    limit = max(1, min(100, int(limit)))
    offset = (page - 1) * limit

    # Build dynamic parameterized query
    where_clauses: List[str] = []
    params: List[Any] = []

    if species and species.strip():
        where_clauses.append("species = ?")
        params.append(species.strip())

    if visual_health and visual_health.strip():
        where_clauses.append("visual_health = ?")
        params.append(visual_health.strip())

    if status and status.strip():
        where_clauses.append("prediction_status = ?")
        params.append(status.strip())

    if start_date and start_date.strip():
        where_clauses.append("timestamp >= ?")
        params.append(start_date.strip())

    if end_date and end_date.strip():
        where_clauses.append("timestamp <= ?")
        params.append(end_date.strip())

    if search and search.strip():
        search_pattern = f"%{search.strip()}%"
        where_clauses.append(
            "(predicted_class LIKE ? OR species LIKE ? OR condition LIKE ? OR image_filename LIKE ?)"
        )
        params.extend([search_pattern, search_pattern, search_pattern, search_pattern])

    where_sql = f"WHERE {' AND '.join(where_clauses)}" if where_clauses else ""

    count_sql = f"SELECT COUNT(*) FROM leaf_analysis {where_sql};"
    query_sql = f"""
        SELECT * FROM leaf_analysis
        {where_sql}
        ORDER BY timestamp DESC, id DESC
        LIMIT ? OFFSET ?;
    """

    try:
        cursor = conn.cursor()
        # Get total matching count
        cursor.execute(count_sql, params)
        total_records = cursor.fetchone()[0]

        # Get page records
        query_params = list(params) + [limit, offset]
        cursor.execute(query_sql, query_params)
        rows = cursor.fetchall()

        records = [row_to_dict(r) for r in rows]
        total_pages = max(1, (total_records + limit - 1) // limit) if total_records > 0 else 1

        pagination = {
            "page": page,
            "limit": limit,
            "total_records": total_records,
            "total_pages": total_pages,
            "has_next": page < total_pages,
            "has_prev": page > 1
        }
        return records, pagination
    finally:
        conn.close()


def get_statistics(db_path: Optional[Union[str, Path]] = None) -> Dict[str, Any]:
    """Computes aggregate analytics over all historical leaf analyses."""
    init_db(db_path)
    conn = get_connection(db_path)
    try:
        cursor = conn.cursor()

        # Overall counts and average confidence
        cursor.execute("""
            SELECT
                COUNT(*) AS total_count,
                SUM(CASE WHEN visual_health = 'Healthy' THEN 1 ELSE 0 END) AS healthy_count,
                SUM(CASE WHEN visual_health = 'Diseased' THEN 1 ELSE 0 END) AS diseased_count,
                SUM(CASE WHEN prediction_status = 'Uncertain' THEN 1 ELSE 0 END) AS uncertain_count,
                AVG(confidence) AS avg_confidence
            FROM leaf_analysis;
        """)
        summary_row = cursor.fetchone()

        total_count = summary_row["total_count"] or 0
        healthy_count = summary_row["healthy_count"] or 0
        diseased_count = summary_row["diseased_count"] or 0
        uncertain_count = summary_row["uncertain_count"] or 0
        avg_conf = float(summary_row["avg_confidence"] or 0.0)

        # Species distribution
        cursor.execute("""
            SELECT species, COUNT(*) as count
            FROM leaf_analysis
            GROUP BY species
            ORDER BY count DESC;
        """)
        species_rows = cursor.fetchall()
        species_dist = [{"species": r["species"], "count": r["count"]} for r in species_rows]
        by_species = {r["species"]: r["count"] for r in species_rows}

        return {
            "total_analyses": total_count,
            "total_records": total_count,
            "healthy_count": healthy_count,
            "diseased_count": diseased_count,
            "uncertain_count": uncertain_count,
            "healthy_percentage": round((healthy_count / total_count * 100.0), 1) if total_count > 0 else 0.0,
            "diseased_percentage": round((diseased_count / total_count * 100.0), 1) if total_count > 0 else 0.0,
            "average_confidence": round(avg_conf, 4),
            "average_confidence_percent": round(avg_conf * 100.0, 2),
            "species_distribution": species_dist,
            "by_species": by_species
        }
    finally:
        conn.close()


def delete_analysis(analysis_id: int, db_path: Optional[Union[str, Path]] = None) -> bool:
    """Deletes a single analysis record by ID. Returns True if record was found and deleted."""
    init_db(db_path)
    conn = get_connection(db_path)
    try:
        with conn:
            cursor = conn.cursor()
            cursor.execute("DELETE FROM leaf_analysis WHERE id = ?;", (analysis_id,))
            return cursor.rowcount > 0
    finally:
        conn.close()


def clear_all_history(db_path: Optional[Union[str, Path]] = None) -> int:
    """Deletes all records from leaf_analysis. Returns total rows cleared."""
    init_db(db_path)
    conn = get_connection(db_path)
    try:
        with conn:
            cursor = conn.cursor()
            cursor.execute("DELETE FROM leaf_analysis;")
            deleted_count = cursor.rowcount
            # Reset autoincrement sequence
            cursor.execute("DELETE FROM sqlite_sequence WHERE name = 'leaf_analysis';")
            logger.info(f"Cleared all {deleted_count} history records from database.")
            return deleted_count
    finally:
        conn.close()
